/// Local database of the phone (docs/datos.md). Opened once at start-up by
/// `bootstrapApp` and injected with `appDatabaseProvider`.
@DriftDatabase(
  tables: [
    Calendars,
    ShiftTypes,
    Patterns,
    PatternRuns,
    DayEntries,
    Holidays,
    AbsenceBalances,
    Settings,
  ],
)
class AppDatabase extends _$AppDatabase {
  AppDatabase(super.e);

  /// True only when this connection created a brand-new database. Opening
  /// an existing empty database or migrating one never sets this flag.
  bool get createdThisOpen => _createdThisOpen;
  bool _createdThisOpen = false;

  /// The schema version this code expects. Bump it together with a new
  /// migration step (see docs/datos.md, "Migraciones").
  static const int latestSchemaVersion = 4;

  @override
  int get schemaVersion => latestSchemaVersion;

  @override
  MigrationStrategy get migration => MigrationStrategy(
    onCreate: (m) async {
      await m.createAll();
      // A database always has a calendar (docs/datos.md, "Esquema v2").
      await _insertMainCalendar();
    },
    // `stepByStep` comes from app_database.steps.dart, regenerated by
    // `dart run drift_dev make-migrations`; each new version adds its
    // `fromXToY:` argument here (docs/datos.md, "Migraciones").
    onUpgrade: stepByStep(
      from1To2: migrateFrom1To2,
      from2To3: migrateFrom2To3,
      from3To4: migrateFrom3To4,
    ),
    beforeOpen: (details) async {
      _createdThisOpen = details.wasCreated;
      await customStatement('PRAGMA foreign_keys = ON');
    },
  );

  Future<void> _insertMainCalendar() {
    final now = DateTime.now().toUtc().millisecondsSinceEpoch;
    return into(calendars).insert(
      CalendarsCompanion.insert(
        id: mainCalendarId,
        name: newMainCalendarName(),
        colorValue: mainCalendarColor,
        sortOrder: 0,
        createdAt: now,
        updatedAt: now,
      ),
    );
  }
}
